
import { useState } from 'react';
import './App.css';

const SAMPLE_REPOSITORIES = [
  'demo-user/livingdocs',
  'demo-user/documentation',
  'demo-user/react-components',
  'demo-user/project-notes',
];

const TEMPLATES = [
  {
    id: 'api',
    name: 'API Documentation',
    description: 'Document functions, parameters, and return values.',
  },
  {
    id: 'technical',
    name: 'Technical Documentation',
    description: 'Explain architecture, modules, and implementation.',
  },
  {
    id: 'readme',
    name: 'README',
    description: 'Create an overview, setup guide, and usage instructions.',
  },
];

const SAMPLE_DOCUMENT = `# LivingDocs Documentation

## Overview
LivingDocs helps developers generate and manage project documentation.

## Main Components
- Repository Management
- GitHub Connection
- Documentation Generation

## Getting Started
1. Select a repository.
2. Choose a documentation template.
3. Generate and review the documentation.

## Notes
This document is sample content generated by the frontend demo.`;

function escapeHtml(value) {
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#039;');
}

// Small Markdown renderer for this frontend demo.
// It intentionally supports common Markdown syntax only.
function renderMarkdown(markdown) {
  const lines = markdown.split('\n');
  const output = [];
  let inList = false;
  let inCode = false;
  let codeLines = [];

  function closeList() {
    if (inList) {
      output.push('</ul>');
      inList = false;
    }
  }

  for (const line of lines) {
    if (line.trim().startsWith('```')) {
      closeList();

      if (inCode) {
        output.push(`<pre><code>${escapeHtml(codeLines.join('\n'))}</code></pre>`);
        codeLines = [];
        inCode = false;
      } else {
        inCode = true;
      }
      continue;
    }

    if (inCode) {
      codeLines.push(line);
      continue;
    }

    if (/^\s*[-*]\s+/.test(line)) {
      if (!inList) {
        output.push('<ul>');
        inList = true;
      }

      output.push(
        `<li>${escapeHtml(line.replace(/^\s*[-*]\s+/, ''))}</li>`
      );
      continue;
    }

    closeList();

    if (/^###\s+/.test(line)) {
      output.push(`<h3>${escapeHtml(line.replace(/^###\s+/, ''))}</h3>`);
    } else if (/^##\s+/.test(line)) {
      output.push(`<h2>${escapeHtml(line.replace(/^##\s+/, ''))}</h2>`);
    } else if (/^#\s+/.test(line)) {
      output.push(`<h1>${escapeHtml(line.replace(/^#\s+/, ''))}</h1>`);
    } else if (/^\d+\.\s+/.test(line)) {
      output.push(`<p>${escapeHtml(line)}</p>`);
    } else if (line.trim() === '---') {
      output.push('<hr />');
    } else if (line.trim() === '') {
      output.push('<div class="markdown-spacer"></div>');
    } else {
      output.push(`<p>${escapeHtml(line)}</p>`);
    }
  }

  closeList();

  if (inCode) {
    output.push(`<pre><code>${escapeHtml(codeLines.join('\n'))}</code></pre>`);
  }

  return output.join('\n');
}

export default function DocumentationManagement() {
  const [repository, setRepository] = useState(SAMPLE_REPOSITORIES[0]);
  const [template, setTemplate] = useState('technical');
  const [sourcePath, setSourcePath] = useState('src/');
  const [status, setStatus] = useState('idle');
  const [document, setDocument] = useState('');
  const [evidence, setEvidence] = useState([]);
  const [error, setError] = useState('');

  const [activeTab, setActiveTab] = useState('edit');
  const [savedDocument, setSavedDocument] = useState('');
  const [versions, setVersions] = useState([]);
  const [selectedVersionId, setSelectedVersionId] = useState('');
  const [compareVersionId, setCompareVersionId] = useState('');
  const [notice, setNotice] = useState('');

  function handleGenerate(event) {
    event.preventDefault();

    setStatus('generating');
    setError('');
    setNotice('');
    setDocument('');
    setSavedDocument('');
    setEvidence([]);
    setVersions([]);
    setSelectedVersionId('');
    setCompareVersionId('');
    setActiveTab('edit');

    // Frontend demo only. No backend or AI service is called.
    window.setTimeout(() => {
      setDocument(SAMPLE_DOCUMENT);
      setSavedDocument(SAMPLE_DOCUMENT);
      setEvidence([
        `Repository: ${repository}`,
        `Source path: ${sourcePath || '(root)'}`,
        `Template: ${TEMPLATES.find((item) => item.id === template)?.name}`,
        'Evidence is simulated for UI testing; source code was not analyzed.',
      ]);
      setStatus('completed');
      setNotice('Sample documentation generated.');
    }, 800);
  }

  function handleReset() {
    setStatus('idle');
    setDocument('');
    setSavedDocument('');
    setEvidence([]);
    setError('');
    setNotice('');
    setVersions([]);
    setSelectedVersionId('');
    setCompareVersionId('');
    setActiveTab('edit');
  }

  function handleSaveDraft() {
    if (!document.trim()) {
      setError('Document content cannot be empty.');
      return;
    }

    setSavedDocument(document);
    setError('');
    setNotice('Draft saved in this page session.');
  }

  function handleCreateVersion() {
    if (!document.trim()) {
      setError('Generate or enter document content before creating a version.');
      return;
    }

    const version = {
      id: `${Date.now()}-${versions.length + 1}`,
      number: versions.length + 1,
      content: document,
      createdAt: new Date().toLocaleString(),
      label: `Version ${versions.length + 1}`,
    };

    setVersions((current) => [...current, version]);
    setSelectedVersionId(version.id);
    setError('');
    setNotice(`${version.label} created.`);
  }

  function handleRollback() {
    const version = versions.find((item) => item.id === selectedVersionId);

    if (!version) {
      setError('Select a version to restore.');
      return;
    }

    const confirmed = window.confirm(
      `Restore ${version.label}? Current unsaved edits will be replaced.`
    );

    if (!confirmed) return;

    setDocument(version.content);
    setSavedDocument(version.content);
    setError('');
    setNotice(`Content restored from ${version.label}.`);
    setActiveTab('edit');
  }

  function handleExport() {
    const blob = new Blob([document], {
      type: 'text/markdown;charset=utf-8',
    });
    const url = URL.createObjectURL(blob);
    const link = window.document.createElement('a');

    link.href = url;
    link.download = 'livingdocs-documentation.md';
    link.click();

    URL.revokeObjectURL(url);
  }

  const selectedVersion = versions.find(
    (version) => version.id === selectedVersionId
  );

  const compareVersion = versions.find(
    (version) => version.id === compareVersionId
  );

  const currentLines = document.split('\n');
  const comparisonLines = compareVersion
    ? compareVersion.content.split('\n')
    : [];

  return (
    <main className="page">
      <section className="login-card documentation-page">
        <h1>Documentation Management</h1>
        <p className="subtitle">
          Generate, preview, edit, and manage documentation versions.
        </p>

        <div className="documentation-status" role="status" aria-live="polite">
          <span className={`documentation-status-badge status-${status}`}>
            {status === 'idle' && 'Ready to generate'}
            {status === 'generating' && 'Generating…'}
            {status === 'completed' && 'Generation completed'}
            {status === 'failed' && 'Generation failed'}
          </span>
        </div>

        <form className="documentation-form" onSubmit={handleGenerate}>
          <label htmlFor="documentation-repository">Repository</label>
          <select
            id="documentation-repository"
            value={repository}
            onChange={(event) => setRepository(event.target.value)}
          >
            {SAMPLE_REPOSITORIES.map((item) => (
              <option key={item} value={item}>{item}</option>
            ))}
          </select>

          <label htmlFor="documentation-source">Source path</label>
          <input
            id="documentation-source"
            value={sourcePath}
            onChange={(event) => setSourcePath(event.target.value)}
            placeholder="e.g. src/"
          />

          <label>Documentation template</label>
          <div className="documentation-template-list">
            {TEMPLATES.map((item) => (
              <label
                key={item.id}
                className={`documentation-template ${template === item.id ? 'selected' : ''}`}
              >
                <input
                  type="radio"
                  name="documentation-template"
                  value={item.id}
                  checked={template === item.id}
                  onChange={() => setTemplate(item.id)}
                />
                <span>
                  <strong>{item.name}</strong>
                  <small>{item.description}</small>
                </span>
              </label>
            ))}
          </div>

          <div className="documentation-actions">
            <button type="submit" disabled={status === 'generating'}>
              {status === 'generating' ? 'Generating…' : 'Generate documentation'}
            </button>
            <button
              type="button"
              className="documentation-secondary-button"
              onClick={handleReset}
            >
              Reset
            </button>
          </div>
        </form>

        {error && (
          <p className="documentation-error" role="alert">{error}</p>
        )}

        {notice && (
          <p className="documentation-notice" role="status">{notice}</p>
        )}

        {status === 'generating' && (
          <p className="documentation-hint">
            Preparing the sample documentation…
          </p>
        )}

        {status === 'completed' && (
          <div className="documentation-result">
            <h2>Generated Documentation</h2>

            <div className="documentation-tabs" role="tablist" aria-label="Documentation views">
              <button
                type="button"
                role="tab"
                aria-selected={activeTab === 'edit'}
                className={activeTab === 'edit' ? 'active' : ''}
                onClick={() => setActiveTab('edit')}
              >
                Edit
              </button>
              <button
                type="button"
                role="tab"
                aria-selected={activeTab === 'preview'}
                className={activeTab === 'preview' ? 'active' : ''}
                onClick={() => setActiveTab('preview')}
              >
                Preview
              </button>
              <button
                type="button"
                role="tab"
                aria-selected={activeTab === 'versions'}
                className={activeTab === 'versions' ? 'active' : ''}
                onClick={() => setActiveTab('versions')}
              >
                Versions ({versions.length})
              </button>
              <button
                type="button"
                role="tab"
                aria-selected={activeTab === 'diff'}
                className={activeTab === 'diff' ? 'active' : ''}
                onClick={() => setActiveTab('diff')}
              >
                Compare
              </button>
            </div>

            {activeTab === 'edit' && (
              <section className="documentation-panel">
                <label htmlFor="documentation-editor">
                  Markdown content
                </label>
                <textarea
                  id="documentation-editor"
                  className="documentation-editor"
                  value={document}
                  onChange={(event) => {
                    setDocument(event.target.value);
                    setNotice('');
                  }}
                  rows={18}
                />

                <div className="documentation-actions">
                  <button type="button" onClick={handleSaveDraft}>
                    Save draft
                  </button>
                  <button
                    type="button"
                    className="documentation-secondary-button"
                    onClick={handleCreateVersion}
                  >
                    Create version
                  </button>
                  <button
                    type="button"
                    className="documentation-secondary-button"
                    onClick={handleExport}
                  >
                    Export Markdown
                  </button>
                </div>

                <p className="documentation-hint">
                  {document === savedDocument
                    ? 'All changes saved in the current page session.'
                    : 'You have unsaved edits.'}
                </p>
              </section>
            )}

            {activeTab === 'preview' && (
              <section className="documentation-preview">
                <div className="documentation-preview-heading">
                  <h3>Document Preview</h3>
                  <span>Markdown preview</span>
                </div>
                {document.trim() ? (
                  <article
                    className="markdown-preview-content"
                    dangerouslySetInnerHTML={{
                      __html: renderMarkdown(document),
                    }}
                  />
                ) : (
                  <p>No content to preview.</p>
                )}
              </section>
            )}

            {activeTab === 'versions' && (
              <section className="documentation-panel">
                <div className="documentation-version-heading">
                  <h3>Version History</h3>
                  <button type="button" onClick={handleCreateVersion}>
                    Create version
                  </button>
                </div>

                {versions.length === 0 ? (
                  <div className="documentation-empty">
                    <h3>No versions yet</h3>
                    <p>Create a version to preserve the current document.</p>
                  </div>
                ) : (
                  <>
                    <label htmlFor="selected-version">Select version</label>
                    <select
                      id="selected-version"
                      value={selectedVersionId}
                      onChange={(event) => setSelectedVersionId(event.target.value)}
                    >
                      {versions.map((version) => (
                        <option key={version.id} value={version.id}>
                          {version.label} — {version.createdAt}
                        </option>
                      ))}
                    </select>

                    {selectedVersion && (
                      <div className="documentation-version-card">
                        <strong>{selectedVersion.label}</strong>
                        <p>Created: {selectedVersion.createdAt}</p>
                        <p>{selectedVersion.content.length} characters</p>
                        <button
                          type="button"
                          className="documentation-secondary-button"
                          onClick={handleRollback}
                        >
                          Restore this version
                        </button>
                      </div>
                    )}
                  </>
                )}
                <p className="documentation-hint">
                  Versions are stored in React state and disappear when this page is reloaded.
                </p>
              </section>
            )}

            {activeTab === 'diff' && (
              <section className="documentation-panel">
                <h3>Compare Documentation</h3>
                <p className="documentation-hint">
                  Choose a saved version to compare it with the current editor content.
                </p>

                <label htmlFor="compare-version">Compare with version</label>
                <select
                  id="compare-version"
                  value={compareVersionId}
                  onChange={(event) => setCompareVersionId(event.target.value)}
                >
                  <option value="">Choose a version</option>
                  {versions.map((version) => (
                    <option key={version.id} value={version.id}>
                      {version.label} — {version.createdAt}
                    </option>
                  ))}
                </select>

                {compareVersion ? (
                  <div className="documentation-diff">
                    <div className="documentation-diff-column">
                      <h4>Saved version</h4>
                      {comparisonLines.map((line, index) => {
                        const changed = currentLines[index] !== line;
                        return (
                          <div
                            key={`${index}-${line}`}
                            className={`documentation-diff-line ${changed ? 'diff-removed' : ''}`}
                          >
                            <span>{changed ? '−' : ' '}</span>
                            {line || ' '}
                          </div>
                        );
                      })}
                    </div>

                    <div className="documentation-diff-column">
                      <h4>Current document</h4>
                      {currentLines.map((line, index) => {
                        const changed = comparisonLines[index] !== line;
                        return (
                          <div
                            key={`${index}-${line}`}
                            className={`documentation-diff-line ${changed ? 'diff-added' : ''}`}
                          >
                            <span>{changed ? '+' : ' '}</span>
                            {line || ' '}
                          </div>
                        );
                      })}
                    </div>
                  </div>
                ) : (
                  <div className="documentation-empty">
                    <p>
                      {versions.length
                        ? 'Select a version to display the comparison.'
                        : 'Create a version first to enable comparison.'}
                    </p>
                  </div>
                )}
              </section>
            )}

            <section className="documentation-evidence">
              <h2>Grounding Evidence</h2>
              <p>
                Demo evidence only. The actual source code has not been analyzed.
              </p>
              <ul>
                {evidence.map((item, index) => (
                  <li key={index}>{item}</li>
                ))}
              </ul>
            </section>
          </div>
        )}

        <p className="documentation-disclaimer">
          Demo mode: generated content, evidence, and version history are sample
          data stored in page state. No backend, GitHub API, or AI service is connected.
        </p>
      </section>
    </main>
  );
}
